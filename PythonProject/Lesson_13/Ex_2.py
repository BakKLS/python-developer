""" Задание 2
Напишите программу для имитации банковского перевода.
Пользователь вводит:
● баланс счёта;
● сумму перевода.
Необходимо:
Преобразовать введённые значения в числа.
Если сумма перевода больше баланса — вывести сообщение
об ошибке.
Если всё прошло успешно — вывести новый баланс.
Использовать else для вывода сообщения об успешном
выполнении операции.
Использовать finally для вывода: Операция завершена.
Обработайте как минимум:
● ValueError;
● ситуацию недостаточного баланса без создания
собственного исключения."""




try:
    balance = float(input("Введите баланс счёта: "))
    transfer_amount = float(input("Введите сумму перевода: "))

    if transfer_amount > balance:
        print("Ошибка: Недостаточно средств на счёте.")
    elif transfer_amount <= 0:
        print("Ошибка: Сумма перевода должна быть больше нуля.")
    else:

        new_balance = balance - transfer_amount

except ValueError:

    print("Ошибка: Введены некорректные данные. Необходимо ввести число.")

else:

    if 'new_balance' in locals():
        print(f"Перевод выполнен успешно! Новый баланс: {new_balance:.2f}")

finally:

    print("Операция завершена.")